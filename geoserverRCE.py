class Http(requests.Session):
    def __init__(self, timeout):
        super().__init__()
        self.trust_env = False
        self.timeout = timeout

    def request(self, method, url, **kw):
        kw.setdefault("timeout", self.timeout)
        kw.setdefault("allow_redirects", False)
        return super().request(method, url, **kw)


def local_name(tag):
    return tag.rsplit("}", 1)[-1]


def resource_url(target, path):
    return target + "/rest/resource/" + urllib.parse.quote(path, safe="/")


def service_url(target, name=""):
    base = target + "/rest/security/usergroupservices"
    return base if not name else base + "/" + urllib.parse.quote(name, safe="")


def require(label, response):
    if not 200 <= response.status_code < 300:
        raise RuntimeError("%s failed: HTTP %s %s" % (label, response.status_code, response.text[:300]))


def ogc_ok(response, root_name):
    if not 200 <= response.status_code < 300:
        return False
    try:
        root = ET.fromstring(response.content)
    except ET.ParseError:
        return False
    attrs = {local_name(k): v for k, v in root.attrib.items()}
    return local_name(root.tag) == root_name and attrs.get("status", "").upper() == "OK"


